// AI failure diagnosis (issue #906)
// ---------------------------------------------------------------------------

/** Typed fix proposal returned by the diagnosis model (fail-closed contract). */
export type FixProposal =
  | { type: 'param_change'; node_id: string; param: string; new_value: unknown }
  | { type: 'selector_update'; node_id: string; new_selector: string }
  | { type: 'wrap_retry'; node_id: string; retry_count?: number; retry_interval_s?: number }
  | { type: 'wrap_trycatch'; node_id: string; exception_type?: string }
  | {
      type: 'insert_precondition';
      after_node_id: string;
      library: string;
      activity: string;
      args?: Record<string, unknown>;
      label?: string;
    };

export interface DiagnosisResult {
  root_cause: string;
  confidence: 'high' | 'medium' | 'low';
  explanation: string;
  proposals: FixProposal[];
}

/** Renderer → main request: failed-run context + current diagram. */
export interface AiDiagnoseFailureRequest {
  /** Generated by the renderer (crypto.randomUUID()); lets ai:cancelDiagnose abort the call. */
  requestId: string;
  providerId: AiProviderId;
  language?: string;
  /** Persisted audit RunRecord (audit.getRun), already redacted core-side. */
  runRecord: {
    run_id?: string;
    process_name?: string;
    status?: string;
    steps?: Array<{
      activity?: string;
      node_id?: string;
      status?: string;
      duration_ms?: number;
      inputs?: Record<string, unknown>;
      output?: unknown;
      error?: string | null;
    }>;
    error?: string | null;
  };
  /** Current diagram document ({nodes, edges}) the proposals will be applied to. */
  diagram: { nodes: Array<{ id: string; data?: Record<string, unknown> }>; edges?: unknown[] };
}

export interface AiDiagnoseFailureResult {
  success: boolean;
  diagnosis?: DiagnosisResult;
  errors?: string[];
  attempts: number;
  tokenUsage?: TokenUsage;
  consentRequired?: boolean;
  consentFeature?: AiConsentFeature;
  consentCategories?: string[];
}

