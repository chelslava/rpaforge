/** One turn of the assistant conversation (renderer-side session state). */
export interface AssistantMessage {
  role: 'user' | 'assistant';
  content: string;
  /** Token/cost accounting for assistant turns (attached by the main process). */
  tokenUsage?: TokenUsage;
  /** Diagram edit proposals extracted from this assistant turn, if any. */
  edits?: FixProposal[];
}

/** Compact context the panel sends with every request (no param values). */
export interface AssistantChatContext {
  /** Compact diagram summary: node ids, labels, types — no param values. */
  diagramNodes: Array<{
    id: string;
    label: string;
    type: string;
    paramKeys?: string[];
  }>;
  selectedNodeId?: string | null;
  /** Redacted last-run error, when the user attaches it. */
  lastError?: string | null;
}

export interface AiAssistantChatRequest {
  /** Generated by the renderer (crypto.randomUUID()); lets ai:cancelAssistant abort the call. */
  requestId: string;
  providerId: AiProviderId;
  language?: string;
  /** Prior conversation turns, oldest first (flattened into the prompt main-side). */
  history: AssistantMessage[];
  userMessage: string;
  context: AssistantChatContext;
}

export interface AiAssistantChatResult {
  success: boolean;
  answer?: string;
  edits?: FixProposal[];
  errors?: string[];
  attempts: number;
  tokenUsage?: TokenUsage;
  consentRequired?: boolean;
  consentFeature?: AiConsentFeature;
  consentCategories?: string[];
}

/** Assistant streaming delta routed by requestId (ai:assistantProgress). */
export interface AiAssistantDeltaEvent {
  requestId: string;
  attempt: number;
  delta: string;
}
